"""Rebuild the local icon font: python -m pip install fonttools[woff]==4.63.0 brotli==1.2.0"""
import hashlib
import io
import json
import sys
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
VERSION = "3.5.1"
URL = f"https://github.com/ryanoasis/nerd-fonts/releases/download/v{VERSION}/NerdFontsSymbolsOnly.zip"
SHA256 = "fdca3682534f6f65e1ccb2345b0362ccf67d9b8eca7c8025330946e93e2473bc"


def main():
    manifest = json.loads((ROOT / "src/components/iconGlyphs.json").read_text(encoding="utf-8"))
    # Only Material Design glyphs are shipped; other upstream symbol families are excluded.
    assert all(g["name"].startswith("md-") for g in manifest.values())
    codepoints = {g["codepoint"] for g in manifest.values()}
    css_names = ("check", "chevronDown", "chevronLeft", "chevron", "chevronDoubleLeft", "chevronDoubleRight")
    css = "/* Generated by scripts/build-icon-font.py from iconGlyphs.json. */\n:root {\n"
    css += "\n".join(f'  --glyph-{name}: "\\{manifest[name]["codepoint"]:x}";' for name in css_names) + "\n}\n"
    out = ROOT / "public/fonts"
    output = out / "suivelle-nerd-symbols.woff2"
    if "--check" in sys.argv:
        assert set(TTFont(output).getBestCmap()) == codepoints, "Registry/font coverage differs"
        assert (ROOT / "src/icon-symbols.css").read_text(encoding="utf-8") == css, "Rebuild generated CSS"
        print(f"Verified {len(codepoints)} glyphs and generated CSS offline")
        return
    with urlopen(URL) as response:
        archive = response.read()
    assert hashlib.sha256(archive).hexdigest() == SHA256, "Upstream archive checksum mismatch"
    out.mkdir(parents=True, exist_ok=True)
    with ZipFile(io.BytesIO(archive)) as z:
        font = TTFont(io.BytesIO(z.read("SymbolsNerdFont-Regular.ttf")), recalcTimestamp=False)
        (out / "NERD-FONTS-LICENSE.txt").write_bytes(z.read("LICENSE"))
    assert codepoints <= font.getBestCmap().keys(), "Mapped glyph missing from source font"
    options = subset.Options()
    options.recalc_timestamp = False
    options.canonical_order = True
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    for record in font["name"].names:
        if record.nameID in (1, 4, 6):
            record.string = "Suivelle Nerd Symbols".replace(" ", "" if record.nameID == 6 else " ").encode(record.getEncoding())
    font.flavor = "woff2"
    font.save(output)
    saved = TTFont(output)
    assert set(saved.getBestCmap()) == codepoints, "Unexpected glyphs in subset"
    (ROOT / "src/icon-symbols.css").write_text(css, encoding="utf-8")
    print(f"{len(codepoints)} glyphs; {output.stat().st_size:,} bytes; sha256 {hashlib.sha256(output.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
