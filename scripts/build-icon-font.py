"""Builds public/fonts/material-symbols-{outlined,rounded,sharp}.woff2 and src/icon-symbols.css.

Icons are Google Material Symbols (three families, variable: weight and fill axes kept, grade and
optical size pinned). The subset holds only the glyphs named in src/components/iconGlyphs.json.

Usage:
  npm i material-symbols --prefix <empty temp dir>      # build-only, never shipped
  python -m pip install "fonttools[woff]" brotli
  python scripts/build-icon-font.py <temp dir>/node_modules/material-symbols
Edit icons by changing the `name` (a Material Symbols icon name) of an entry; the codepoint is
looked up from the font. Keep the semantic keys stable: they are saved in page and workspace data.
"""
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "src/components/iconGlyphs.json"
FONTS = ROOT / "public/fonts"
STYLES = ["outlined", "rounded", "sharp"]
CSS_OUT = ROOT / "src/icon-symbols.css"
CSS_KEYS = ["check", "chevronDown", "chevronLeft", "chevron", "chevronDoubleLeft", "chevronDoubleRight"]

package = Path(sys.argv[1])
registry = json.loads(REGISTRY.read_text(encoding="utf8"))
for style in STYLES:
    source = TTFont(package / f"material-symbols-{style}.woff2")
    by_name = {glyph: code for code, glyph in source.getBestCmap().items() if code >= 0xE000}
    for key, entry in registry.items():
        if entry["name"] not in by_name:
            sys.exit(f"{key}: '{entry['name']}' is not a Material Symbols icon in the {style} font")
        # The three families share codepoints; the outlined one is the reference.
        if style == "outlined":
            entry["codepoint"] = by_name[entry["name"]]
        elif by_name[entry["name"]] != entry["codepoint"]:
            sys.exit(f"{key}: codepoint differs in the {style} font")
    font = instancer.instantiateVariableFont(source, {"GRAD": 0, "opsz": 20})
    options = subset.Options()
    options.layout_features = []
    options.notdef_outline = False
    options.flavor = "woff2"
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted({e["codepoint"] for e in registry.values()}))
    subsetter.subset(font)
    font.flavor = "woff2"
    out = FONTS / f"material-symbols-{style}.woff2"
    font.save(out)
    print(style, out.stat().st_size, "bytes")
REGISTRY.write_text(json.dumps(registry, indent=2) + "\n", encoding="utf8")

lines = ["/* Generated by scripts/build-icon-font.py from iconGlyphs.json. */", ":root {"]
lines += [f'  --glyph-{key}: "\{registry[key]["codepoint"]:x}";' for key in CSS_KEYS]
CSS_OUT.write_text("\n".join(lines + ["}", ""]), encoding="utf8")
print(f"{len(registry)} icons")
